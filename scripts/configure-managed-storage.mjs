import {readFileSync, writeFileSync, existsSync} from "node:fs";
import {resolve} from "node:path";

const source = resolve(process.argv[2] || ".");
const configured = process.env.SIYUAN_MANAGED_STORAGE_ORIGIN || "";
let origin = "";
if (configured) {
    const url = new URL(configured);
    if (url.protocol !== "https:" || !url.hostname || url.username || url.password ||
        url.pathname !== "/" || url.search || url.hash || /[\s\\]/.test(configured)) {
        throw new Error("SIYUAN_MANAGED_STORAGE_ORIGIN must be a credential-free HTTPS origin");
    }
    origin = url.origin;
}
const target = resolve(source, "kernel/model/managed_storage_origin.go");
const marker = "// Code generated by configure-managed-storage.mjs; DO NOT EDIT.";
if (existsSync(target) && !readFileSync(target, "utf8").includes(marker)) {
    throw new Error("Refusing to overwrite an unrecognized source file");
}
writeFileSync(target, `// SiYuan - https://github.com/siyuan-note/siyuan
// Copyright (c) 2020-present, b3log.org
// SPDX-License-Identifier: AGPL-3.0-or-later

${marker}

package model

func init() { ManagedStorageOrigin = ${JSON.stringify(origin)} }
`);
console.log(origin ? "Managed storage HTTPS origin configured for this build" : "Managed storage origin unset; manual storage remains available");
